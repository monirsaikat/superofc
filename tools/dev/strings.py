"""Adds or updates UI strings in src/SuperOfc.Desktop/Resources/Strings.resx.

Usage:
  python -I tools/dev/strings.py path/to/new-strings.txt
The input file has one "Key=Value" per line; blank lines and lines starting with # are ignored.
Keys use PascalCase with an area prefix, e.g. Login_Title, Employees_New.
Existing keys are overwritten; the resx stays sorted by key so diffs are small.
"""
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RESX = ROOT / "src" / "SuperOfc.Desktop" / "Resources" / "Strings.resx"
DESIGNER = RESX.with_name("Strings.Designer.cs")

HEADER = """<?xml version="1.0" encoding="utf-8"?>
<root>
  <resheader name="resmimetype"><value>text/microsoft-resx</value></resheader>
  <resheader name="version"><value>2.0</value></resheader>
  <resheader name="reader"><value>System.Resources.ResXResourceReader, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
  <resheader name="writer"><value>System.Resources.ResXResourceWriter, System.Windows.Forms, Version=4.0.0.0, Culture=neutral, PublicKeyToken=b77a5c561934e089</value></resheader>
</root>
"""


def load() -> dict:
    if not RESX.exists():
        return {}
    tree = ET.parse(RESX)
    return {d.get("name"): (d.findtext("value") or "") for d in tree.getroot().findall("data")}


def escape(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def save(entries: dict) -> None:
    lines = HEADER.rstrip().splitlines()[:-1]
    for key in sorted(entries, key=str.lower):
        lines.append(f'  <data name="{key}" xml:space="preserve"><value>{escape(entries[key])}</value></data>')
    lines.append("</root>")
    RESX.parent.mkdir(parents=True, exist_ok=True)
    RESX.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_designer(entries: dict) -> None:
    """Writes the typed accessor class (WPF markup compile runs before MSBuild resource generation)."""
    out = [
        "// <auto-generated>Generated by tools/dev/strings.py. Do not edit by hand.</auto-generated>",
        "#nullable enable",
        "namespace SuperOfc.Desktop.Resources;",
        "",
        "public static class Strings",
        "{",
        "    private static System.Resources.ResourceManager? resourceManager;",
        "",
        "    public static System.Resources.ResourceManager ResourceManager =>",
        "        resourceManager ??= new System.Resources.ResourceManager(\"SuperOfc.Desktop.Resources.Strings\", typeof(Strings).Assembly);",
        "",
        "    public static System.Globalization.CultureInfo? Culture { get; set; }",
        "",
        "    /// <summary>Called once per key when the UI language has no text for it and English is shown instead (P8-T4).</summary>",
        "    public static System.Action<string, string>? MissingTranslation { get; set; }",
        "",
        "    private static readonly System.Collections.Concurrent.ConcurrentDictionary<string, byte> Reported = new();",
        "",
        "    public static string Get(string key)",
        "    {",
        "        var culture = Culture ?? System.Globalization.CultureInfo.CurrentUICulture;",
        "        var value = ResourceManager.GetString(key, culture);",
        "        if (value is null)",
        "        {",
        "            Report(key, culture);",
        "            return key;",
        "        }",
        "",
        "        if (MissingTranslation is not null && culture.TwoLetterISOLanguageName != \"en\" && !Translated(key, culture))",
        "        {",
        "            Report(key, culture);",
        "        }",
        "",
        "        return value;",
        "    }",
        "",
        "    private static bool Translated(string key, System.Globalization.CultureInfo culture)",
        "    {",
        "        for (var c = culture; !c.Equals(System.Globalization.CultureInfo.InvariantCulture); c = c.Parent)",
        "        {",
        "            if (ResourceManager.GetResourceSet(c, true, false)?.GetString(key) is not null)",
        "            {",
        "                return true;",
        "            }",
        "        }",
        "",
        "        return false;",
        "    }",
        "",
        "    private static void Report(string key, System.Globalization.CultureInfo culture)",
        "    {",
        "        if (Reported.TryAdd(culture.Name + \"/\" + key, 0))",
        "        {",
        "            MissingTranslation?.Invoke(key, culture.Name);",
        "        }",
        "    }",
    ]
    for key in sorted(entries, key=str.lower):
        out.append("")
        out.append(f"    public static string {key} => Get(\"{key}\");")
    out.append("}")
    DESIGNER.write_text("\n".join(out) + "\n", encoding="utf-8")


def main() -> None:
    entries = load()
    added = 0
    for path in sys.argv[1:]:
        for raw in Path(path).read_text(encoding="utf-8").splitlines():
            line = raw.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, value = line.split("=", 1)
            entries[key.strip()] = value.strip().replace("\\n", "\n")
            added += 1
    save(entries)
    write_designer(entries)
    print(f"{added} strings merged, {len(entries)} total")


if __name__ == "__main__":
    main()
